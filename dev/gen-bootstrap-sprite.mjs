#!/usr/bin/env node
/*---------------------------------------------------------------------------------------------
 *  Generates the vendored Bootstrap Icons subset the Settings shell draws inline
 *  (`openideBootstrapIcons.ts`).
 *
 *  Bootstrap's SVGs are FILLED shapes on a 16 grid, not strokes on a 24 grid like Tabler's, so
 *  each path carries its own `fill-rule` when the source sets one — dropping it turns a ring into
 *  a disc. The extractor keeps it.
 *
 *  Usage, from the repo root, with bootstrap-icons extracted somewhere:
 *      node dev/gen-bootstrap-sprite.mjs <path-to-bootstrap-icons/icons>
 *--------------------------------------------------------------------------------------------*/

import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(REPO, 'vscode/src/vs/workbench/contrib/openideSettings/browser/openideBootstrapIcons.ts');
const ICONS = process.argv[2];
if (!ICONS) { throw new Error('usage: gen-bootstrap-sprite.mjs <path-to-bootstrap-icons/icons>'); }

/** The subset Settings actually draws. Keep it minimal: this ships as source, not as a font. */
const NAMES = [
	'house', 'star', 'plug', 'chat-square-dots', 'mic', 'database', 'stars', 'hdd-rack', 'book',
	'lightning-charge', 'slash-lg', 'terminal', 'robot', 'diagram-3', 'bell', 'globe', 'sliders',
	'pencil', 'layout-sidebar', 'window', 'sliders2', 'display', 'shield-lock', 'translate',
	'stack', 'cursor-text', 'cursor', 'search', 'fonts', 'text-paragraph', 'arrow-left-right', 'files',
	'pip', 'lightbulb', 'floppy', 'palette', 'signpost-split', 'layout-three-columns', 'wrench',
	'bullseye', 'record-circle', 'plus-circle', 'volume-up', 'eye', 'folder2-open', 'bug', 'flask',
	'git', 'box-seam', 'list-check', 'exclamation-circle', 'file-earmark-text', 'chat', 'cloud',
	'clock-history', 'journal-code', 'clipboard', 'command', 'cloud-arrow-down', 'bar-chart',
	'arrow-clockwise', 'share', 'rocket-takeoff', 'three-dots', 'shield-check', 'chevron-down',
	'puzzle', 'x-lg', 'plus-lg', 'check-lg', 'trash', 'copy', 'box-arrow-up-right', 'key',
	'link-45deg', 'info-circle', 'exclamation-triangle', 'check-circle', 'x-circle', 'arrow-repeat',
];

const entries = [];
for (const name of NAMES) {
	const svg = readFileSync(join(ICONS, `${name}.svg`), 'utf8');
	const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
	if (viewBox !== '0 0 16 16') { throw new Error(`${name}: unexpected viewBox ${viewBox}`); }
	const paths = [];
	for (const m of svg.matchAll(/<path\b([^>]*)\/?>/g)) {
		const attrs = m[1];
		const d = /\sd="([^"]+)"/.exec(attrs)?.[1];
		if (!d) { throw new Error(`${name}: <path> without d`); }
		paths.push(/fill-rule="evenodd"/.test(attrs) ? [d, 1] : [d]);
	}
	if (!paths.length) { throw new Error(`${name}: no paths — is it a <circle>/<rect> icon?`); }
	entries.push([name, paths]);
}

const body = entries
	.map(([name, paths]) => `\t'${name}': [${paths.map(p => (p.length === 2 ? `['${p[0]}', 1]` : `'${p[0]}'`)).join(', ')}],`)
	.join('\n');

writeFileSync(OUT, `/*---------------------------------------------------------------------------------------------
 *  Copyright (c) OpenIDE. All rights reserved.
 *  Licensed under the MIT License. See License.txt in the project root for license information.
 *--------------------------------------------------------------------------------------------*/

/*---------------------------------------------------------------------------------------------
 *  OpenIDE — vendored Bootstrap Icons subset (https://icons.getbootstrap.com, MIT), the same set
 *  the product icon theme (theme-defaults/producticons/openide-bootstrap-*) uses for the
 *  codicons, so Settings and the workbench speak ONE icon language: a single 16×16 grid of filled
 *  shapes.
 *
 *  Data only — name → paths, generated by dev/gen-bootstrap-sprite.mjs. The DOM is built with
 *  \`createElementNS\`, never with markup strings: the workbench enforces Trusted Types and an
 *  innerHTML sprite would be rejected outright.
 *
 *  A path is either a \`d\` string or \`[d, 1]\`, where the 1 means the source set
 *  \`fill-rule="evenodd"\` — without it a ring fills in as a disc.
 *--------------------------------------------------------------------------------------------*/

type IconPath = string | readonly [string, 1];

const BOOTSTRAP_ICON_PATHS = {
${body}
} as const satisfies Record<string, readonly IconPath[]>;

export type BootstrapIconName = keyof typeof BOOTSTRAP_ICON_PATHS;

export function isBootstrapIconName(name: string): name is BootstrapIconName {
	return Object.prototype.hasOwnProperty.call(BOOTSTRAP_ICON_PATHS, name);
}

const SVG_NS = 'http://www.w3.org/2000/svg';

/**
 * Appends one Bootstrap icon as an inline SVG sized in CSS pixels. The shape is filled with
 * \`currentColor\`, so it takes the color of its surroundings like a codicon does.
 */
export function appendBootstrapIcon(parent: HTMLElement, name: BootstrapIconName, size = 16): SVGSVGElement {
	const paths: readonly IconPath[] = BOOTSTRAP_ICON_PATHS[name];
	const svg = parent.ownerDocument.createElementNS(SVG_NS, 'svg');
	svg.setAttribute('viewBox', '0 0 16 16');
	svg.setAttribute('width', String(size));
	svg.setAttribute('height', String(size));
	svg.setAttribute('fill', 'currentColor');
	svg.setAttribute('aria-hidden', 'true');
	for (const entry of paths) {
		const path = parent.ownerDocument.createElementNS(SVG_NS, 'path');
		path.setAttribute('d', typeof entry === 'string' ? entry : entry[0]);
		if (typeof entry !== 'string') { path.setAttribute('fill-rule', 'evenodd'); }
		svg.appendChild(path);
	}
	parent.appendChild(svg);
	return svg;
}
`);
console.log(`sprite: ${entries.length} icons, ${entries.reduce((n, [, p]) => n + p.length, 0)} paths`);
